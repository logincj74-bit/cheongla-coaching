create table public.cheongla_mbti_learning_articles (
  id uuid primary key default gen_random_uuid(),
  category text not null check (category in ('groups','parent_sj','parent_sp','parent_nf','parent_nt')),
  title text not null check (char_length(btrim(title)) between 1 and 120),
  body text not null check (char_length(btrim(body)) between 1 and 20000),
  archived_at timestamptz,
  revision integer not null default 1
);

create unique index cheongla_one_published_mbti_learning_article
  on public.cheongla_mbti_learning_articles (category) where archived_at is null;

alter table public.cheongla_mbti_learning_articles enable row level security;
revoke all on public.cheongla_mbti_learning_articles from public, anon, authenticated;
grant select, delete on public.cheongla_mbti_learning_articles to authenticated;
grant insert (category, title, body), update (title, body, archived_at)
  on public.cheongla_mbti_learning_articles to authenticated;

create policy mbti_learning_article_member_read on public.cheongla_mbti_learning_articles
  for select to authenticated
  using (archived_at is null and (select exists (
    select 1 from public.cheongla_profiles
    where id = (select auth.uid()) and approval_status = 'approved' and membership_state = 'active'
  )));

create policy mbti_learning_article_principal_manage on public.cheongla_mbti_learning_articles
  for all to authenticated
  using ((select exists (
    select 1 from public.cheongla_profiles
    where id = (select auth.uid()) and approval_status = 'approved'
      and membership_state = 'active' and role in ('owner', 'english_director', 'math_director')
  )))
  with check ((select exists (
    select 1 from public.cheongla_profiles
    where id = (select auth.uid()) and approval_status = 'approved'
      and membership_state = 'active' and role in ('owner', 'english_director', 'math_director')
  )));

